#' Partially Optimized Bayesian Phase II Efficacy and Futility Design
#'
#' Tools for partially optimized Bayesian single-arm phase II designs with a
#' binary endpoint and efficacy and futility stopping. Subject to prespecified
#' error constraints, the design selects response-count boundaries that minimize
#' the final grey-zone probability. The package provides decision tables and
#' operating-characteristic calculations.
#'
#' @references Zhou, H., Lee, J. J., and Yuan, Y. (2017). BOP2: Bayesian
#'   optimal design for phase II clinical trials with simple and complex
#'   endpoints. *Statistics in Medicine*, 36(21), 3302-3314.
#'   \doi{10.1002/sim.7338}
#'
#'   Xu, X., Hashimoto, A., Yimer, B. B., and Takeda, K. (2025).
#'   BOP2-FE: Bayesian optimal phase II design with futility and
#'   efficacy-stopping boundaries. *Journal of Biopharmaceutical Statistics*.
#'   \doi{10.1080/10543406.2025.2558142}
